// Offline DOM integration tests. This is not a visual browser or native-window test.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(process.env.RELAY_TEST_DEPS || import.meta.url);
const {JSDOM}=require('jsdom');
const html=readFileSync('apps/desktop/dist/index.html','utf8');
const script=html.match(/<script[^>]+src="([^"]+)"[^>]*><\/script>/);
assert.ok(script,'Build the frontend before running UI tests.');
const dom=new JSDOM(html.replace(script[0],''),{url:'https://relay-demo.invalid',runScripts:'outside-only',pretendToBeVisual:true});
const {window}=dom;
// jsdom does not implement native dialog modal behavior. Stub only this platform seam.
window.HTMLDialogElement.prototype.showModal=function(){this.setAttribute('open','');};
window.HTMLDialogElement.prototype.close=function(){this.removeAttribute('open');};
window.eval(readFileSync(`apps/desktop/dist${script[1]}`,'utf8'));
const settle=()=>new Promise(resolve=>setTimeout(resolve,40));
const text=()=>window.document.body.textContent;
function button(label){const result=[...window.document.querySelectorAll('button')].find(b=>b.textContent.trim()===label);assert.ok(result,`Button not found: ${label}`);return result;}
async function click(label){button(label).click();await settle();}
await settle();
assert.ok(text().includes('Operations overview'));
assert.equal(window.document.querySelectorAll('.run-row').length,8);
await click('Evidence3');
assert.ok(text().includes('Purchase order & goods receipt'));
await click('Approve resolution');
assert.ok(window.document.querySelector('dialog[open]'));
await click('Record approval');
assert.ok(text().includes('Add a reason to the audit record.'));
const textarea=window.document.querySelector('textarea');
const setValue=Object.getOwnPropertyDescriptor(window.HTMLTextAreaElement.prototype,'value').set;
setValue.call(textarea,'Verified against the receipt; fixture test only.');
textarea.dispatchEvent(new window.Event('input',{bubbles:true}));
await settle();
await click('Record approval');
assert.ok(!window.document.querySelector('dialog[open]'));
await click('Overview');
assert.ok(text().includes('Verified against the receipt; fixture test only.'));
const saved=JSON.parse(window.localStorage.getItem('relay-demo-v1'));
assert.equal(saved.runs.find(r=>r.id==='RUN-1048').status,'Completed');
await click('Replay labLab');
await click('Run fixture replay');
assert.ok(text().includes('Approval requested using policy v3.2'));
await click('Evaluations');
await click('Run fixture checks');
assert.ok(text().includes('4 deterministic fixture checks passed'));
await click('Releases');
assert.equal(button('Production promotion blocked').disabled,true);
await click('Simulate shadow rollout');
assert.ok(text().includes('Shadow demo'));
await click('Roll back demo');
assert.ok(text().includes('Staged'));
await click('Knowledge');
await click('Memory');
assert.ok(text().includes('Reviewed operational memory'));
await click('Data studio');
await click('Preference pairs');
assert.ok(text().includes('Rejected response'));
await click('Connections');
assert.ok(text().includes('ERP fixture'));
await click('AI employees');
await click('Try demo');
await click('Create demo run');
assert.equal(window.document.querySelectorAll('.run-row').length,9);
assert.ok(text().includes('Harbor Supplies'));
dom.window.close();
console.log('DOM integration passed: queue, evidence, required review note, persisted approval, replay, fixture checks, blocked promotion, shadow rollback, knowledge, data, connectors, and new run.');
