"""Deterministic OpenAPI/TypeScript contract generation; no running server required."""

import argparse
import json
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "services/runtime"))


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "anyOf" in schema or "oneOf" in schema:
        return " | ".join(
            ts_type(item) for item in schema.get("anyOf", schema.get("oneOf"))
        )
    kind = schema.get("type")
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind in {"integer", "number"}:
        return "number"
    if kind == "array":
        return "Array<" + ts_type(schema.get("items", {})) + ">"
    if kind == "object" or "properties" in schema:
        props = schema.get("properties", {})
        required = schema.get("required", [])
        fields = [
            json.dumps(key) + ("" if key in required else "?") + ": " + ts_type(value)
            for key, value in sorted(props.items())
        ]
        additional = schema.get("additionalProperties", not bool(props))
        if additional:
            fields.append(
                "[key: string]: "
                + (
                    ts_type(additional)
                    if isinstance(additional, dict) and not props
                    else "unknown"
                )
            )
        return "{ " + "; ".join(fields) + " }"
    if not schema or set(schema) <= {"title", "description", "default"}:
        return "unknown"
    raise ValueError("Unsupported schema: " + json.dumps(schema))


def snapshot() -> dict:
    from veya.api.app import create_app
    from veya.config import Settings

    (ROOT / "artifacts").mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(
        prefix="veya-contract-", dir=ROOT / "artifacts"
    ) as temporary:
        settings = Settings(
            "test",
            "http://127.0.0.1:4318",
            Path(temporary),
            "fixture_contract",
            "env:VEYA_TEST_TOKEN",
        )
        return create_app(settings, "fixture_contract_token_" + "x" * 32).openapi()


def render(schema: dict, version: int) -> str:
    definitions = schema["components"]["schemas"]
    return (
        "// Generated by packages/contracts/generate.py; do not edit.\n"
        + f"export const contractVersion = {version} as const;\n"
        + "\n".join(
            f"export type {name} = {ts_type(value)};"
            for name, value in sorted(definitions.items())
        )
        + "\n"
    )


def breaking(previous: dict, current: dict) -> bool:
    before = previous["components"]["schemas"]
    after = current["components"]["schemas"]
    # Deliberately conservative: changing an existing shape requires a version bump.
    return any(after.get(key) != value for key, value in before.items()) or any(
        current["paths"].get(key) != value for key, value in previous["paths"].items()
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--version", type=int)
    args = parser.parse_args()
    folder = Path(__file__).parent
    schema_path, types_path = folder / "openapi.json", folder / "src/index.ts"
    old = json.loads(schema_path.read_text()) if schema_path.exists() else None
    version = args.version or (old["contract_version"] if old else 1)
    schema = snapshot()
    if version < 1 or (old and version < old["contract_version"]):
        parser.exit(1, "Contract versions must be positive and cannot decrease.\n")
    if (
        old
        and breaking(old["openapi"], schema)
        and version <= old["contract_version"]
        and not args.check
    ):
        parser.exit(
            1,
            "Existing API shape changed. Review compatibility and supply a greater --version.\n",
        )
    schema_text = (
        json.dumps(
            {"contract_version": version, "openapi": schema}, sort_keys=True, indent=2
        )
        + "\n"
    )
    types = render(schema, version)
    if args.check:
        if (
            not schema_path.exists()
            or not types_path.exists()
            or schema_path.read_text() != schema_text
            or types_path.read_text() != types
        ):
            parser.exit(
                1, "API contract drift: review and regenerate versioned contracts.\n"
            )
        print("PASS: OpenAPI and TypeScript contracts match")
    else:
        types_path.parent.mkdir(exist_ok=True)
        schema_path.write_text(schema_text, encoding="utf-8")
        types_path.write_text(types, encoding="utf-8")


if __name__ == "__main__":
    main()
